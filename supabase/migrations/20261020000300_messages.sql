-- M3: messages, read state, mention parsing, unread summary, and Realtime authorization
-- for the private Broadcast topics (typing indicators).

-- ---------------------------------------------------------------------------
-- Sending rules
-- ---------------------------------------------------------------------------

-- True when the user may post in the channel: SEND_MESSAGES there and not timed out.
create or replace function public.can_send(p_channel uuid, p_user uuid default auth.uid())
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  ch record;
begin
  select id, server_id, type into ch from public.channels where id = p_channel;
  if not found or ch.type not in ('text', 'thread') then
    return false;
  end if;
  if public.channel_permissions(p_channel, p_user) & 2 = 0 then -- SEND_MESSAGES
    return false;
  end if;
  return not exists (
    select 1 from public.server_members
    where server_id = ch.server_id and user_id = p_user and timeout_until > now()
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Messages
-- ---------------------------------------------------------------------------

create type public.message_type as enum ('default', 'reply', 'system', 'thread_created', 'pin');

create table public.messages (
  -- Generated by the client, so a retried send can't create a duplicate.
  id uuid primary key,
  channel_id uuid not null references public.channels (id) on delete cascade,
  author_id uuid default auth.uid() references public.profiles (id) on delete set null,
  content text not null default '',
  type public.message_type not null default 'default',
  reply_to_id uuid references public.messages (id) on delete set null,
  attachments jsonb not null default '[]'::jsonb,
  mentions uuid[] not null default '{}',
  mention_roles uuid[] not null default '{}',
  mention_everyone boolean not null default false,
  pinned_at timestamptz,
  pinned_by uuid references public.profiles (id) on delete set null,
  edited_at timestamptz,
  created_at timestamptz not null default now(),
  search tsvector generated always as (to_tsvector('simple', content)) stored,
  has_link boolean generated always as (content ~* 'https?://') stored,
  constraint messages_content_length check (char_length(content) <= 2000),
  constraint messages_not_empty
    check (
      type not in ('default', 'reply')
      or char_length(btrim(content)) > 0
      or jsonb_array_length(attachments) > 0
    ),
  constraint messages_attachments_array check (jsonb_typeof(attachments) = 'array')
);

create index messages_channel_created_idx on public.messages (channel_id, created_at desc, id desc);
create index messages_author_idx on public.messages (author_id);
create index messages_mentions_idx on public.messages using gin (mentions);
create index messages_search_idx on public.messages using gin (search);
create index messages_pinned_idx on public.messages (channel_id, pinned_at) where pinned_at is not null;

-- Parses <@user>, <@&role> and @everyone/@here out of content. Role and @everyone
-- mentions only count when allowed: mentionable roles, or MENTION_EVERYONE.
create or replace function public.messages_extract_mentions()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  ch record;
  perms bigint;
begin
  select id, server_id into ch from public.channels where id = new.channel_id;
  perms := case when ch.server_id is null then 0
                else public.channel_permissions(new.channel_id, new.author_id) end;

  select coalesce(array_agg(distinct p.id), '{}') into new.mentions
  from regexp_matches(new.content, '<@([0-9a-fA-F-]{36})>', 'g') as m(g)
  join public.profiles p on p.id = public.try_uuid(m.g[1]);

  if ch.server_id is null then
    new.mention_roles := '{}';
  else
    select coalesce(array_agg(distinct r.id), '{}') into new.mention_roles
    from regexp_matches(new.content, '<@&([0-9a-fA-F-]{36})>', 'g') as m(g)
    join public.roles r on r.id = public.try_uuid(m.g[1])
    where r.server_id = ch.server_id
      and not r.is_default
      and (r.mentionable or perms & 8 <> 0); -- MENTION_EVERYONE can ping any role
  end if;

  new.mention_everyone := ch.server_id is not null
    and perms & 8 <> 0
    and new.content ~ '(^|[^\w`])@(everyone|here)\M';
  return new;
end;
$$;

create or replace function public.messages_before_insert()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- Clients can't backdate messages; the seed script (service role) can.
  if current_user = 'authenticated' then
    new.created_at := now();
    new.author_id := auth.uid();
    new.pinned_at := null;
    new.pinned_by := null;
    new.edited_at := null;
    if new.type not in ('default', 'reply') then
      raise exception 'Clients can only send normal messages.';
    end if;
  end if;

  if new.reply_to_id is not null then
    if not exists (
      select 1 from public.messages where id = new.reply_to_id and channel_id = new.channel_id
    ) then
      new.reply_to_id := null;
    else
      new.type := 'reply';
    end if;
  end if;
  return new;
end;
$$;

-- Authors may only change the text. Pinning goes through pin_message() (security definer).
create or replace function public.messages_before_update()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.id := old.id;
  new.channel_id := old.channel_id;
  new.author_id := old.author_id;
  new.type := old.type;
  new.reply_to_id := old.reply_to_id;
  new.attachments := old.attachments;
  new.created_at := old.created_at;
  if current_user = 'authenticated' then
    new.pinned_at := old.pinned_at;
    new.pinned_by := old.pinned_by;
  end if;
  if new.content is distinct from old.content then
    new.edited_at := now();
  else
    new.edited_at := old.edited_at;
  end if;
  return new;
end;
$$;

create trigger messages_before_insert
  before insert on public.messages
  for each row execute function public.messages_before_insert();

create trigger messages_before_update
  before update on public.messages
  for each row execute function public.messages_before_update();

-- Runs after the guards so mentions use the final content.
create trigger messages_zz_extract_mentions
  before insert or update of content on public.messages
  for each row execute function public.messages_extract_mentions();

alter table public.messages enable row level security;

create policy "viewers read messages"
  on public.messages for select to authenticated
  using (public.can_view_channel(channel_id));

create policy "senders post messages"
  on public.messages for insert to authenticated
  with check (author_id = (select auth.uid()) and public.can_send(channel_id));

create policy "authors edit their messages"
  on public.messages for update to authenticated
  using (author_id = (select auth.uid()))
  with check (author_id = (select auth.uid()));

create policy "authors and moderators delete messages"
  on public.messages for delete to authenticated
  using (
    author_id = (select auth.uid())
    or public.channel_permissions(channel_id) & 4 <> 0 -- MANAGE_MESSAGES
  );

-- ---------------------------------------------------------------------------
-- Channel activity (kept out of Realtime; feeds unread state)
-- ---------------------------------------------------------------------------

create table public.channel_activity (
  channel_id uuid primary key references public.channels (id) on delete cascade,
  last_message_id uuid,
  last_message_at timestamptz not null,
  message_count bigint not null default 0
);

alter table public.channel_activity enable row level security;

create policy "viewers read channel activity"
  on public.channel_activity for select to authenticated
  using (public.can_view_channel(channel_id));

create or replace function public.messages_after_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.channel_activity (channel_id, last_message_id, last_message_at, message_count)
  values (new.channel_id, new.id, new.created_at, 1)
  on conflict (channel_id) do update
    set last_message_id = case when excluded.last_message_at >= public.channel_activity.last_message_at
                               then excluded.last_message_id else public.channel_activity.last_message_id end,
        last_message_at = greatest(public.channel_activity.last_message_at, excluded.last_message_at),
        message_count = public.channel_activity.message_count + 1;
  return null;
end;
$$;

create trigger messages_after_insert
  after insert on public.messages
  for each row execute function public.messages_after_insert();

