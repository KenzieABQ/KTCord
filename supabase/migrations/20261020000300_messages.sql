-- Idempotent send: retrying with the same id returns the stored message instead of duplicating.
-- SECURITY INVOKER, so the insert is checked by the RLS policy above.
create or replace function public.send_message(
  p_id uuid,
  p_channel uuid,
  p_content text,
  p_reply_to uuid default null,
  p_attachments jsonb default '[]'::jsonb
)
returns setof public.messages
language plpgsql
set search_path = ''
as $$
begin
  if not public.can_send(p_channel) then
    if exists (
      select 1 from public.channels c
      join public.server_members sm on sm.server_id = c.server_id and sm.user_id = auth.uid()
      where c.id = p_channel and sm.timeout_until > now()
    ) then
      raise exception 'You''re timed out and can''t send messages right now.';
    end if;
    raise exception 'You don''t have permission to send messages in this channel.';
  end if;

  insert into public.messages (id, channel_id, content, reply_to_id, attachments)
  values (p_id, p_channel, coalesce(p_content, ''), p_reply_to, coalesce(p_attachments, '[]'::jsonb))
  on conflict (id) do nothing;

  return query select * from public.messages where id = p_id and author_id = auth.uid();
end;
$$;

revoke execute on function public.send_message(uuid, uuid, text, uuid, jsonb) from public, anon;
revoke execute on function public.mark_read(uuid, uuid) from public, anon;
revoke execute on function public.get_unread_state() from public, anon;
grant execute on function public.send_message(uuid, uuid, text, uuid, jsonb) to authenticated;
grant execute on function public.mark_read(uuid, uuid) to authenticated;
grant execute on function public.get_unread_state() to authenticated;

