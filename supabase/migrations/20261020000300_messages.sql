create table public.read_states (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  channel_id uuid not null references public.channels (id) on delete cascade,
  last_read_message_id uuid,
  last_read_at timestamptz not null default now(),
  constraint read_states_unique unique (user_id, channel_id)
);

alter table public.read_states enable row level security;

create policy "users read their own read state"
  on public.read_states for select to authenticated
  using (user_id = (select auth.uid()));

create policy "users write their own read state"
  on public.read_states for insert to authenticated
  with check (user_id = (select auth.uid()) and public.can_view_channel(channel_id));

create policy "users update their own read state"
  on public.read_states for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- Marks a channel read up to a message. Never moves the marker backwards.
create or replace function public.mark_read(p_channel uuid, p_message uuid)
returns timestamptz
language plpgsql
set search_path = ''
as $$
declare
  read_at timestamptz;
begin
  select created_at into read_at from public.messages
  where id = p_message and channel_id = p_channel;
  if read_at is null then
    read_at := now();
  end if;

  insert into public.read_states (user_id, channel_id, last_read_message_id, last_read_at)
  values (auth.uid(), p_channel, p_message, read_at)
  on conflict (user_id, channel_id) do update
    set last_read_message_id = case when excluded.last_read_at > public.read_states.last_read_at
                                    then excluded.last_read_message_id
                                    else public.read_states.last_read_message_id end,
        last_read_at = greatest(public.read_states.last_read_at, excluded.last_read_at);
  return read_at;
end;
$$;

-- One row per channel the user can read in their servers: when it last had a message, when they
-- last read it (their join time if never), and how many unread messages mention them.
create or replace function public.get_unread_state()
returns table (
  channel_id uuid,
  server_id uuid,
  last_message_at timestamptz,
  last_read_at timestamptz,
  mention_count bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  with me as (select auth.uid() as uid),
  visible as (
    select c.id, c.server_id, a.last_message_at,
           coalesce(rs.last_read_at, sm.joined_at) as last_read_at
    from public.server_members sm
    join me on sm.user_id = me.uid
    join public.channels c on c.server_id = sm.server_id and c.type in ('text', 'thread')
    join public.channel_activity a on a.channel_id = c.id
    left join public.read_states rs on rs.channel_id = c.id and rs.user_id = me.uid
    where public.can_view_channel(c.id)
  )
  select v.id, v.server_id, v.last_message_at, v.last_read_at,
    case when v.last_message_at <= v.last_read_at then 0 else (
      select count(*) from public.messages m, me
      where m.channel_id = v.id
        and m.created_at > v.last_read_at
        and m.author_id is distinct from me.uid
        and (
          me.uid = any (m.mentions)
          or m.mention_everyone
          or m.mention_roles && array(
            select mr.role_id from public.member_roles mr
            where mr.server_id = v.server_id and mr.user_id = me.uid
          )
        )
    ) end
  from visible v;
$$;

