-- Private Broadcast/Presence topics "channel:<uuid>" (typing) are open to the channel's viewers.
create policy "channel viewers use channel topics"
  on realtime.messages for select to authenticated
  using (
    realtime.topic() like 'channel:%'
    and public.can_view_channel(public.try_uuid(substr(realtime.topic(), 9)))
  );

create policy "channel viewers broadcast on channel topics"
  on realtime.messages for insert to authenticated
  with check (
    realtime.topic() like 'channel:%'
    and public.can_view_channel(public.try_uuid(substr(realtime.topic(), 9)))
  );
